"""Task model: a task is a titled list of shell steps turned into one script.

Each step runs in its own subshell with `set -eo pipefail`, so the first
failing command aborts only that step; the summary at the end lists every
failed step.  Scripts are plain bash so users can review exactly what runs.
"""

import itertools
import os

from .. import APP_NAME, VERSION
from . import sources, system
from .util import HELPER, SHELL_LIB, desktop_user, runtime_dir, shq

_ids = itertools.count(1)


class Step:
    __slots__ = ("title", "code")

    def __init__(self, title, code):
        self.title = title
        self.code = code if isinstance(code, str) else "\n".join(code)


class Task:
    """A unit of work for the console queue.

    root     -- run with administrator rights (pkexec/sudo/su)
    refresh  -- names of data groups the UI should reload afterwards
    on_done  -- callback(task, success) run in the GTK main loop
    stop_on_error -- skip the remaining steps after a failed one (for steps that
                     depend on each other, e.g. add a repository -> install from it)
    """

    def __init__(self, title, steps, root=True, refresh=(), on_done=None, summary="", stop_on_error=False):
        self.id = next(_ids)
        self.title = title
        self.steps = [s if isinstance(s, Step) else Step(*s) for s in steps]
        self.root = root
        self.refresh = set(refresh)
        self.on_done = on_done
        self.summary = summary
        self.stop_on_error = stop_on_error
        self.state = "queued"       # queued, running, done, failed, cancelled
        self.exit_code = None

    def add(self, title, code):
        self.steps.append(Step(title, code))
        return self


class Context:
    """Values injected at the top of every generated script."""

    def __init__(self, release=None):
        self.release = release or system.detect_release()
        self.user, self.uid, self.home = desktop_user()

    def header(self):
        r = self.release
        return {
            "TARGET_USER": self.user,
            "TARGET_UID": str(self.uid),
            "TARGET_HOME": self.home,
            "BRANCH": r.get("branch", "unknown"),
            "DEBIAN_CODENAME": r.get("debian_codename") or system.STABLE,
            "VENDOR_CODENAME": r.get("vendor_codename") or system.STABLE,
            "STABLE_CODENAME": system.STABLE,
            "TESTING_CODENAME": system.TESTING,
            "IS_LMDE": "1" if r.get("is_lmde") else "0",
            "DEBIAN_KEYRING": sources.DEBIAN_KEYRING,
            "DEBOS_HELPER_PATH": HELPER,
        }


def build_script(task, ctx):
    lines = [
        "#!/bin/bash",
        f"# Generated by {APP_NAME} {VERSION}: {task.title}",
        "# " + ("Every command below runs as root." if task.root else "Runs with your normal user rights."),
        f"DEBOS_TITLE={shq(task.title)}",
    ]
    for key, val in ctx.header().items():
        lines.append(f"{key}={shq(val)}")
    lines += [
        # ARCH stays a plain shell variable: exported, it would break kernel and DKMS
        # builds (Kbuild reads $ARCH and expects "x86", not "amd64")
        "unset ARCH CROSS_COMPILE",
        'ARCH="$(dpkg --print-architecture 2>/dev/null || uname -m)"',
        "export TARGET_USER TARGET_HOME BRANCH DEBIAN_CODENAME VENDOR_CODENAME",
        f"source {shq(SHELL_LIB)} || {{ echo 'Debos shell library is missing.'; exit 1; }}",
        "cd /tmp || exit 1",
        f"debos_begin {len(task.steps)}",
        "",
    ]
    for step in task.steps:
        # step code is NOT indented: heredoc terminators (EOF, DEBOS_EOF) must start at column 0
        lines += [f"__step {shq(step.title)}", "(", "set -eo pipefail"]
        lines += step.code.splitlines()
        lines += [")", "__done $?" + (" || debos_stop" if task.stop_on_error else ""), ""]
    lines.append("debos_end")
    return "\n".join(lines) + "\n"


def write_script(task, ctx):
    """Write the task script into the private runtime dir and return (script, status) paths."""
    base = runtime_dir()
    script = os.path.join(base, f"task-{os.getpid()}-{task.id}.sh")
    status = os.path.join(base, f"task-{os.getpid()}-{task.id}.status")
    for path in (status, status + ".tmp"):
        try:
            os.remove(path)
        except FileNotFoundError:
            pass
    fd = os.open(script, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(build_script(task, ctx))
    os.chmod(script, 0o600)
    return script, status
